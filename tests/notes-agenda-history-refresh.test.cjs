"use strict";
const assert = require("node:assert/strict");
const cal = require("../additional/notes/calendar/ZentralNotesCalendar.js");
const fs = require("node:fs");
(async () => {
  const files = new Map();
  const io = { join: (...p) => p.join("/"), readUTF8: async p => { if (!files.has(p)) { const e = new Error("not found"); e.code = "ENOENT"; throw e; } return files.get(p); }, writeUTF8: async (p, v) => files.set(p, v), exists: async p => files.has(p) };
  let writes = 0;
  const opts = { io, getDir: () => "/n", now: () => 1234, setTimer: () => 1, clearTimer() {}, onWrite: () => writes++ };
  const a = cal.createReminderHistoryStore(opts), b = cal.createReminderHistoryStore(opts);
  await a.open(); await b.open();
  assert.equal(typeof a.on, "function");
  const events = [], remote = [];
  const off = a.on(e => events.push(e)); b.on(e => remote.push(e));
  const entry = { itemId: "id", occurrenceId: "occ", action: "done", at: 1234 };
  assert.ok(a.append(entry));
  assert.equal(a.stateFor("id", "occ"), "done");
  assert.equal(events.length, 1); assert.equal(events[0].itemId, "id"); assert.equal(events[0].occurrenceId, "occ");
  await a.flush(); assert.equal(writes, 1);
  assert.equal(await b.refresh(), 1); assert.equal(b.stateFor("id", "occ"), "done");
  assert.equal(remote.length, 1); assert.deepEqual(remote[0].identities, [{ itemId: "id", occurrenceId: "occ" }]);
  assert.equal(await b.refresh(), 0); assert.equal(remote.length, 1);
  off(); a.append({ ...entry, action: "reopened", at: 1235 }); assert.equal(events.length, 1);
  assert.deepEqual(cal.agendaPendingItems([{id: 1}, {id: 2}, {id: 3}], item => item.id === 1 ? "done" : item.id === 2 ? "dismissed" : "pending").map(x => x.id), [3]);
  const ui = fs.readFileSync(require.resolve("../additional/notes/ZentralNotes.uc.js"), "utf8");
  assert.match(ui, /agendaPendingItems\(CALENDAR_PART\.expandRange\(page\.items, from, to\), reminderLifecycleState\)/);
  assert.match(ui, /offCalendarHistory\s*=\s*store\.items\?\.history\?\.on/);
  assert.match(ui, /agendaHistoryUnsub\s*=\s*store\.items\?\.history\?\.on/);
  assert.match(ui, /msg\.kind === "reminder-history"/);
  console.log("Agenda history refresh tests passed");
})().catch(e => { console.error(e); process.exitCode = 1; });
