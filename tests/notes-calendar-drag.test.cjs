"use strict";
const assert = require("node:assert/strict");
const C = require("../additional/notes/calendar/ZentralNotesCalendar.js");
assert.deepEqual([5, 10, 15, 30, 60, "30", 0, 7, null].map(C.cleanCalendarSnap), [5, 10, 15, 30, 60, 30, 15, 15, 15]);
const zone = "Europe/Warsaw";
const time = (date, clock) => C.zonedDateTimeToMs(date, clock, zone);
const make = (start, end, x = {}) => C.makeItem({ id: "drag-event", summary: "Meeting", start: { dateTime: new Date(start).toISOString() }, end: { dateTime: new Date(end).toISOString() }, x: { kind: "event", src: "manual", ...x } }, 0);
const original = make(time("2026-03-27", "10:10"), time("2026-03-27", "11:10"));
const place = C.calendarMovePlacement(original, "2026-03-27", 615, "2026-03-28", 675, zone, 15);
assert.deepEqual(place, { date: "2026-03-28", minute: 675 });
assert.deepEqual(C.calendarMovePlacement(original, "2026-03-27", 615, "2026-03-27", 625, zone, 30), { date: "2026-03-27", minute: 630 }, "target follows the configured snap grid");
const moved = C.calendarMoveTimedEvent(original, place, zone, 1000);
assert.equal(moved.start.dateTime, new Date(time("2026-03-28", "11:15")).toISOString());
assert.equal(Date.parse(moved.end.dateTime) - Date.parse(moved.start.dateTime), 3600000);
assert.equal(original.start.dateTime, new Date(time("2026-03-27", "10:10")).toISOString(), "original is never mutated");
const clipped = C.calendarMovePlacement(original, "2026-03-28", 30, "2026-03-29", 60, zone, 15);
assert.deepEqual(clipped, { date: "2026-03-28", minute: 645 }, "a clipped segment moves relative to its actual start, not the segment date");
const spring = C.calendarMoveTimedEvent(original, { date: "2026-03-29", minute: 150 }, zone, 1000);
assert.equal(spring.start.dateTime, new Date(time("2026-03-29", "03:00")).toISOString(), "missing spring wall time advances to the first valid time");
const fall = C.calendarMoveTimedEvent(original, { date: "2026-10-25", minute: 150 }, zone, 1000);
assert.equal(fall.start.dateTime, new Date("2026-10-25T00:30:00.000Z").toISOString(), "ambiguous fall wall time chooses the earlier instant");
const reminder = C.makeItem({ id: "timed-reminder", summary: "Call", start: original.start, x: { kind: "reminder", src: "manual" } }, 0);
const movedReminder = C.calendarMoveTimedItem(reminder, place, zone, 1000);
assert.equal(movedReminder.start.dateTime, new Date(time("2026-03-28", "11:15")).toISOString());
assert.equal(movedReminder.end, undefined, "moving a reminder does not create an event end");
const allDay = C.makeItem({ id: "all-day-reminder", summary: "All day", start: { date: "2026-03-28" }, x: { kind: "reminder", src: "manual" } }, 0);
const allDayMoved = C.calendarMoveAllDayReminder(allDay, "2026-03-28", "2026-03-30", 1000);
assert.equal(allDayMoved.start.date, "2026-03-30", "all-day drag uses civil dates across the DST change");
assert.equal(allDayMoved.end, undefined);
assert.equal(allDay.start.date, "2026-03-28");
assert.equal(C.calendarMoveAllDayReminder({ ...allDay, recurrence: ["RRULE:FREQ=DAILY"] }, "2026-03-28", "2026-03-30"), null);
assert.equal(C.calendarMoveAllDayReminder(allDay, "bad", "2026-03-30"), null);
assert.equal(C.calendarMoveAllDayReminder({}, "2026-03-28", "2026-03-30"), null);
assert.equal(C.calendarMoveTimedItem({}, place, zone), null);
assert.equal(C.calendarMoveTimedEvent(null, place, zone), null);
const listed = make(time("2026-03-27", "10:00"), time("2026-03-27", "11:00"), { src: "list" });
assert.equal(C.calendarMoveTimedEvent(listed, place, zone, 1000).x.moved, "1");
assert.equal(C.calendarMoveTimedEvent({ ...original, recurrence: ["RRULE:FREQ=DAILY"] }, place, zone), null);
assert.equal(C.calendarMoveTimedEvent({ ...original, x: { ...original.x, series: "series" } }, place, zone), null);
assert.equal(C.calendarMoveTimedEvent(original, { date: "2026-02-30", minute: 45 }, zone), null);
assert.equal(C.calendarMovePlacement(original, "bad", 0, "2026-03-28", 0, zone), null);
console.log("calendar timed drag model passed");
const endPlacement = C.calendarResizePlacement(original, "end", "2026-03-27", 670, "2026-03-27", 700, zone, 15);
assert.deepEqual(endPlacement, { date: "2026-03-27", minute: 705 }, "resize placement uses the selected edge rather than the event start");
const stretched = C.calendarResizeTimedEvent(original, "end", endPlacement, zone, 15, 1000);
assert.equal(stretched.start.dateTime, original.start.dateTime);
assert.equal(stretched.end.dateTime, new Date(time("2026-03-27", "11:45")).toISOString());
const minResize = C.calendarResizeTimedEvent(original, "end", { date: "2026-03-27", minute: 0 }, zone, 30, 1000);
assert.equal(Date.parse(minResize.end.dateTime), Date.parse(original.start.dateTime) + 30 * 60000, "end cannot cross the minimum duration");
const minStart = C.calendarResizeTimedEvent(original, "start", { date: "2026-03-28", minute: 0 }, zone, 15, 1000);
assert.equal(Date.parse(minStart.start.dateTime), Date.parse(original.end.dateTime) - 15 * 60000, "start cannot cross the end");
const listResize = C.calendarResizeTimedEvent(listed, "end", { date: "2026-03-29", minute: 150 }, zone, 15, 1000);
assert.equal(listResize.end.dateTime, new Date(time("2026-03-29", "03:00")).toISOString(), "DST gaps advance to a valid time");
assert.equal(listResize.x.moved, "1");
assert.equal(C.calendarResizeTimedEvent(reminder, "end", endPlacement, zone), null);
assert.equal(C.calendarResizeTimedEvent({ ...original, recurrence: ["RRULE:FREQ=DAILY"] }, "end", endPlacement, zone), null);
assert.equal(C.calendarResizeTimedEvent(original, "wrong", endPlacement, zone), null);
assert.equal(C.calendarResizePlacement(original, "wrong", "2026-03-27", 0, "2026-03-27", 30, zone), null);
console.log("calendar timed resize model passed");
const forwardRange = C.calendarDraftRange("2026-03-27", 615, "2026-03-28", 690, zone, 15);
assert.deepEqual(forwardRange, { startDate: "2026-03-27", startTime: "10:15", endDate: "2026-03-28", endTime: "11:30" });
assert.deepEqual(C.calendarDraftRange("2026-03-28", 690, "2026-03-27", 615, zone, 15), forwardRange, "reverse drag selects the same range");
assert.deepEqual(C.calendarDraftRange("2026-03-29", 150, "2026-03-29", 240, zone, 30), { startDate: "2026-03-29", startTime: "03:00", endDate: "2026-03-29", endTime: "04:00" }, "spring DST gap is resolved consistently");
assert.equal(C.calendarDraftRange("2026-03-27", 615, "2026-03-27", 615, zone, 15), null, "zero-length selection is refused");
assert.equal(C.calendarDraftRange("bad", 615, "2026-03-27", 700, zone, 15), null);
console.log("calendar drag-create model passed");
