"use strict";
const assert = require("node:assert/strict");
const C = require("../additional/notes/calendar/ZentralNotesCalendar.js");
const { createFakeZen } = require("./helpers/fake-zen-browser.cjs");
const now = new Date(2026, 10, 13, 12).getTime(), today = C.dayStart(now);
const date = (days) => C.addDays(today, days) + 12 * 3600000;
const make = (id, offset, x = {}, recurrence = []) => C.makeItem({ id, summary: id, start: { dateTime: new Date(date(offset)).toISOString() }, recurrence, x: { kind: "reminder", src: "manual", ...x } }, now);
const records = [make("too-old", -8), make("first", -7), make("middle", -3), make("done", -2), make("hidden", -1, { agendaWindow: { enabled: false } }), make("last", -1), make("today", 0)];
records.push(C.makeItem({ id: "old-event", summary: "old-event", start: { dateTime: new Date(date(-1)).toISOString() }, end: { dateTime: new Date(date(-1) + 3600000).toISOString() }, x: { kind: "event" } }, now));
const recurring = make("series", -2, {}, ["RRULE:FREQ=DAILY;COUNT=3"]); records.push(recurring);
const isDone = (item) => item.id === "done" || (item.x?.series === "series" && C.localDateKey(C.itemRange(item)[0]) === C.localDateKey(date(-1)));
const bucket = C.agendaOverdueProjection(records, now, { days: 7, cap: 2, isDone });
assert.equal(bucket.key, "day:overdue"); assert.equal(bucket.label, "Overdue");
assert.equal(bucket.count, 4, "total excludes completed, hidden, events and items beyond seven civil days");
assert.deepEqual(bucket.items.slice(0, 2).map((entry) => entry.itemId), ["first", "middle"], "oldest overdue reminders first");
assert.equal(bucket.items[2].key, "more:overdue"); assert.equal(bucket.items[2].label, "+2 more");
assert.equal(C.agendaOverdueProjection(records, now, { enabled: false }), null);
assert.equal(C.agendaOverdueProjection([records[0]], now, { days: 7 }), null);
assert.equal(C.agendaOverdueProjection(records, now, { days: 1, cap: 10, isDone }).count, 1, "look-back can be narrowed");
{
  let clock = now, timer = null;
  const api = { ensureRoot: () => true, list: () => [], add: () => true, update() {}, reorder() {}, removeAll() {} };
  const c = C.createZenAgenda({ api, getItems: () => [records[1]], now: () => clock, getOverdue: () => ({ enabled: true, days: 7 }), setTimer: (fn, ms) => { timer = { fn, at: clock + ms }; return 1; }, clearTimer() {} });
  c.runNow(); assert.equal(c.projection[0].key, "day:overdue"); assert.equal(timer.at, C.addDays(today, 1), "overdue-only buckets wake on expiry boundary");
  clock = timer.at; timer.fn(); assert.equal(c.projection.length, 0, "expired look-back entries leave at midnight"); c.destroy();
}
(async () => {
  const h = createFakeZen({ prefs: { "zen.workspace.zentral.notes.agenda_folder": true, "zen.workspace.zentral.notes.agenda_overdue": true } });
  try {
    await h.seam.ensureStore(); h.fireTimer(6500); await Promise.resolve();
    const currentDay = C.dayStart(Date.now()), yesterday = C.addDays(currentDay, -1) + 12 * 3600000;
    for (let i = 0; i < 12; i++) h.seam.store.items.upsert(C.makeItem({ id: `overdue-${i}`, summary: `Overdue ${i}`, start: { dateTime: new Date(yesterday + i * 60000).toISOString() }, x: { kind: "reminder", src: "manual" } }, yesterday - 1000));
    h.seam.store.items.upsert(C.makeItem({ id: "today-item", summary: "Today item", start: { dateTime: new Date(currentDay + 13 * 3600000).toISOString() }, x: { kind: "reminder", src: "manual" } }, currentDay));
    const projection = h.seam.agendaController.runNow(); assert.equal(projection[0].key, "day:overdue");
    const folder = h.document.querySelector('zen-folder[bgalazka-notes-agenda-day="overdue"]');
    const allDays = h.document.querySelectorAll("zen-folder[bgalazka-notes-agenda-day]");
    assert.ok(allDays[0] === folder, "Overdue is above Today");
    assert.ok(folder, "real host creates the Overdue folder"); assert.equal(folder.getAttribute("bgalazka-notes-agenda-count"), "12");
    const more = folder.querySelectorAll("tab").find((tab) => tab.getAttribute("bgalazka-notes-agenda-item") === "more:overdue");
    assert.ok(more); assert.equal(more.getAttribute("label"), "+2 more"); assert.equal(more.getAttribute("bgalazka-notes-agenda-day"), C.localDateKey(yesterday));
    const down = h.emit("mousedown", more, { button: 0, clientX: 10, clientY: 10 }); assert.equal(down.defaultPrevented, false);
    h.emit("mouseup", more, { button: 0, clientX: 10, clientY: 10 });
    const event = h.emit("click", more, { button: 0, clientX: 10, clientY: 10 }); assert.equal(event.defaultPrevented, true);
    for (let i = 0; i < 4; i++) await new Promise((r) => setImmediate(r));
    assert.equal(h.seam.store.meta.calendarCursor, C.localDateKey(yesterday), "More opens the first hidden overdue day");
    assert.equal(h.seam.store.meta.calendarView, "day");
    h.resetOperations(); h.seam.agendaController.runNow(); assert.deepEqual(h.operations, [], "unchanged overdue projection is structurally idempotent");
    h.seam.store.items.history.append({ itemId: "overdue-0", occurrenceId: "overdue-0", action: "done", at: Date.now() });
    h.seam.agendaController.runNow(); assert.equal(folder.getAttribute("bgalazka-notes-agenda-count"), "11");
    const snoozeTarget = folder.querySelectorAll("tab").find((tab) => tab.getAttribute("bgalazka-notes-agenda-item-id") === "overdue-1");
    const snoozeMenu = h.document.createXULElement("menupopup"); snoozeMenu.id = "tabContextMenu"; h.document.body.append(snoozeMenu);
    h.window.TabContextMenu = { contextTab: snoozeTarget }; h.emit("popupshowing", snoozeMenu);
    const snooze = snoozeMenu.querySelectorAll("menuitem").find((entry) => entry.getAttribute("label") === "Snooze +1 day"); assert.ok(snooze);
    snooze.dispatchEvent(new h.Ev("command")); for (let i = 0; i < 4; i++) await new Promise((r) => setImmediate(r));
    h.seam.agendaController.runNow(); assert.ok(!folder.querySelectorAll("tab").includes(snoozeTarget), "snoozing past midnight removes the overdue occurrence");
    h.setPref("zen.workspace.zentral.notes.agenda_overdue_cap", 30);
    const note = h.seam.store.create("# Legacy note reminder");
    let schedules = 0; const oldSchedule = h.seam.agendaController.schedule;
    h.seam.agendaController.schedule = (...args) => { schedules++; return oldSchedule(...args); };
    assert.ok(h.seam.store.setReminder(note.id, yesterday));
    assert.ok(schedules > 0, "legacy note reminder changes schedule Agenda reconciliation");
    h.seam.agendaController.runNow();
    const legacy = folder.querySelectorAll("tab").find((tab) => tab.getAttribute("bgalazka-notes-agenda-item-id") === "note-reminder:" + note.id);
    assert.ok(legacy, "front-matter reminder appears in overdue bucket");
    const menu = h.document.createXULElement("menupopup"); menu.id = "tabContextMenu"; h.document.body.append(menu);
    h.window.TabContextMenu = { contextTab: legacy }; h.emit("popupshowing", menu);
    const done = menu.querySelectorAll("menuitem").find((entry) => entry.getAttribute("label") === "Mark as done");
    assert.ok(done && !done.hasAttribute("disabled"), "legacy reminder can be completed from its Agenda menu");
    done.dispatchEvent(new h.Ev("command"));
    for (let i = 0; i < 4; i++) await new Promise((r) => setImmediate(r));
    assert.equal(h.seam.store.get(note.id).remind, 0, "Done clears the legacy source schedule");
    h.seam.agendaController.runNow(); assert.ok(!folder.querySelectorAll("tab").includes(legacy));
    const removedNote = h.seam.store.create("# Removed legacy reminder");
    assert.ok(h.seam.store.setReminder(removedNote.id, yesterday)); h.seam.agendaController.runNow();
    schedules = 0; await h.seam.store.deleteForever(removedNote.id);
    assert.ok(schedules > 0, "removing a legacy reminder note still schedules reconciliation");
    h.setPref("zen.workspace.zentral.notes.agenda_overdue", false); h.seam.agendaController.runNow();
    assert.equal(h.document.querySelector('zen-folder[bgalazka-notes-agenda-day="overdue"]'), null);
  } finally { await h.destroy(); }
  console.log("Agenda overdue projection and real host passed");
})().catch((error) => { console.error(error); process.exitCode = 1; });
