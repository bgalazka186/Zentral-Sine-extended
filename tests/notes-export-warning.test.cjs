"use strict";
const assert = require("node:assert/strict"), fs = require("node:fs"), vm = require("node:vm");
const window = { __zentralNotesTestSeam: {}, ZentralRuntime: { register() {} } }; window.window = window;
vm.runInNewContext(fs.readFileSync(require.resolve("../additional/notes/ZentralNotes.uc.js"), "utf8"), { window, globalThis: { Services: {} }, ChromeUtils: {}, URL, Date, JSON, Math, Promise, RegExp, Number, Map, Set, console });
const scan = window.__zentralNotesTestSeam.core.markdownExportWarnings;
assert.equal(typeof scan, "function");
const source = "# Plan\n[TOC]\n> [!NOTE]- Detail\n> Text\n![[other note]]\n%%calendar%%\n- 2026-11-14 09:00 Reminder %%zn-item-id:abcd1%%\n";
assert.deepEqual(Array.from(scan(source)).sort(), ["calendar", "callout", "toc", "transclusion"]);
assert.deepEqual(Array.from(scan("`![[literal]]`\n```md\n[TOC]\n> [!NOTE] demo\n%%calendar%%\n```\nplain text")), [], "examples in code are not live syntax");
assert.deepEqual(Array.from(scan("ordinary [link](https://example.com)\n- [ ] task\n![image](assets/n1/x.png)")), []);
assert.equal(source.includes("%%zn-item-id:abcd1%%"), true);
console.log("Markdown export warning scan passed");
const convert = window.__zentralNotesTestSeam.core.portableMarkdownExportBody;
assert.equal(typeof convert, "function");
const target = Object.freeze({ id: "other_id", body: "# Other note\n\n## Part\nText", updated: 2 });
const note = Object.freeze({ id: "note_a", body: "---\ntitle: A\ncustom: keep\n---\n# Plan\n[TOC]\n\n## Work\n> [!NOTE]- Details\n> Important\n![[Other note#Part]]\n![[photo.png|300]]\n%%calendar: Work%%\n- 2026-11-14 09:00 Call %%zn-item-id:abcd1%%\n`![[literal]]`\n```\n[TOC]\n> [!TIP] example\n```\n", updated: 1 });
const output = convert(note, [target, note], new Map([["other_id", "Other note.md"]]), []);
assert.match(output, /^---\ntitle: A\ncustom: keep\n---\n/);
assert.match(output, /## Table of Contents[\s\S]*\[Work\]\(#work\)/);
assert.match(output, /> \*\*NOTE\*\* — Details\n> Important/);
assert.match(output, /\[Other note > Part\]\(Other%20note\.md#part\)/);
assert.match(output, /!\[photo\.png\]\(assets\/note_a\/photo\.png\)/);
assert.match(output, /<!-- %%calendar: Work%% -->/);
assert.match(output, /<!-- %%zn-item-id:abcd1%% -->/);
assert.match(output, /`!\[\[literal\]\]`\n```\n\[TOC\]\n> \[!TIP\] example\n```/);
assert.equal(note.body.includes("[TOC]"), true, "source is never mutated");
const missing = convert({ id: "note_a", body: "![[Missing note]]" }, [], new Map(), []);
assert.match(missing, /Missing note/, "unresolved embed target is never silently discarded");
const tricky = { id: "note_a", body: '---\ntitle: "Front"\ndescription: |\n  ```\n  ![[ignored]]\n---\n# Actual\n> [!TIP] Hello\n![[Other note]]\n' };
assert.deepEqual(Array.from(scan(tricky.body)).sort(), ["callout", "transclusion"], "front matter is neither scanned nor treated as an open code fence");
const trickOut = convert(tricky, [target], new Map(), []);
assert.ok(trickOut.startsWith('---\ntitle: "Front"\ndescription: |\n  ```\n  ![[ignored]]\n---\n'), "front matter is copied byte-for-byte");
assert.match(trickOut, /> \*\*TIP\*\* — Hello/);
assert.match(trickOut, /\[Other note\]\(other_id\.md\)/);
const chooseBody = window.__zentralNotesTestSeam.core.markdownExportBody;
assert.equal(typeof chooseBody, "function");
assert.equal(chooseBody(note, [note, target], new Map(), [], "raw"), note.body, "raw preserves every original character");
assert.equal(chooseBody(note, [note, target], new Map(), [], "portable"), convert(note, [note, target], new Map(), []));
assert.match(chooseBody({ id: "source", body: "[[Other note]]" }, [target], new Map(), [], ""), /\[Other note\]\(other_id\.md\)/, "unwarned default retains the existing export contract");
const comment = '<!--\n```\n![[private example]]\n-->\n> [!TIP] Real\n![[Other note]]\n<!-- %%calendar%% ![[untouched]] -->\n';
assert.deepEqual(Array.from(scan(comment)).sort(), ["callout", "transclusion"], "examples in HTML comments do not trigger warnings or change fence state");
const commentOut = convert({ id: "note_a", body: comment }, [target], new Map(), []);
assert.match(commentOut, /^<!--\n```\n!\[\[private example\]\]\n-->/, "HTML comments are preserved verbatim");
assert.match(commentOut, /<!-- %%calendar%% !\[\[untouched\]\] -->/, "inline HTML comments remain untouched");
assert.match(commentOut, /> \*\*TIP\*\* — Real/);
const hidden = '# Secret\nVisible %%private -- text%% end\n%%calendar: Work--Review%%\n';
assert.deepEqual(Array.from(scan(hidden)).sort(), ["calendar", "hidden comment"]);
const hiddenOut = convert({ id: "note_a", body: hidden }, [], new Map(), []);
assert.match(hiddenOut, /<!-- %%private -&#45; text%% -->/);
assert.match(hiddenOut, /<!-- %%calendar: Work-&#45;Review%% -->/);
assert.doesNotMatch(hiddenOut, /`%%/); // hidden text must not become visible literal code
const hiddenEmbed = '%%![[Other note]] %%\n%%calendar%%\n';
