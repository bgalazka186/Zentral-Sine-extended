"use strict";
const assert = require("node:assert/strict");
const { createFakeZen } = require("./helpers/fake-zen-browser.cjs");
const C = require("../additional/notes/calendar/ZentralNotesCalendar.js");
(async () => {
  const h = createFakeZen({ prefs: { "zen.workspace.zentral.notes.debug_perf": true, "zen.workspace.zentral.notes.agenda_folder": true } });
  await h.seam.ensureStore();
  const { createPerfSampler, createReminderScheduler } = h.window.__zentralNotesTestSeam.core;
  let active = false, clockCalls = 0, tick = 0;
  const sampler = createPerfSampler({ enabled: () => active, now: () => { clockCalls++; return tick; } });
  const original = Promise.resolve("value");
  const work = sampler.wrapAsync("async", () => original);
  assert.equal(work(), original); sampler.recordBytes("bytes", "é"); await original; assert.equal(clockCalls, 0); assert.equal(sampler.rows().length, 0);
  active = true; const result = work(); assert.equal(result, original); tick = 7; await result; await Promise.resolve();
  sampler.recordBytes("bytes", "é");
  assert.equal(sampler.rows().find((x) => x.name === "async").total, 7);
  assert.equal(sampler.rows().find((x) => x.name === "bytes").total, 2);
  assert.match(sampler.report(), /bytes/);
  let rejected = Promise.reject(new Error("failure"));
  const wrapped = sampler.wrapAsync("reject", () => rejected); assert.equal(wrapped(), rejected); await assert.rejects(rejected, /failure/);
  const perf = h.window.__zentralNotesPerf;
  const start = C.addDays(C.dayStart(Date.now()), 1) + 12 * 3600000;
  h.seam.store.items.upsert(C.makeItem({ id: "perf", summary: "Ź test", start: { dateTime: new Date(start).toISOString() }, x: { kind: "reminder", src: "manual" } }));
  h.seam.agendaController.runNow();
  h.seam.store.items.history.append({ itemId: "perf", action: "done", at: Date.now() });
  await h.seam.store.items.flush(); await Promise.resolve();
  const scheduler = createReminderScheduler({ store: h.seam.store, now: () => Date.now(), setTimer: () => 1, clearTimer() {}, onDue() {} });
  scheduler.start(); await Promise.resolve(); scheduler.destroy();
  const names = perf.rows().map((row) => row.name);
  for (const name of ["agenda.runNow", "reminders.calendarCandidates", "reminders.pass", "history.write", "history.bytes", "calendar.write", "calendar.bytes"]) assert.ok(names.includes(name), `missing real path sample ${name}`);
  const parent = new h.El("div"); h.document.body.append(parent);
  const adapter = { position: "fixed", host: parent, attach: (root) => parent.append(root), getArea: () => ({ left: 0, top: 0, width: 1000, height: 700 }), watch: () => () => {}, setActive() {}, rewatch() {} };
  const sheet = h.window.__zentralNotesTestSeam.core.createSheet({ store: h.seam.store, adapter, env: { getPref: (_k, d) => d, setPref() {}, openLink() {}, copyText() {} }, ensureStore: h.seam.ensureStore });
  await sheet.open();
  sheet.root.all().find((el) => el.title === "All notes").click();
  assert.ok(perf.rows().some((row) => row.name === "calendar.render"), "real calendar rendering is sampled");
  sheet.destroy();
  h.setPref("zen.workspace.zentral.notes.debug_perf", false); perf.reset(); h.seam.agendaController.runNow(); await h.seam.store.items.flush();
  assert.equal(perf.rows().length, 0); await h.destroy();
  console.log("performance instrumentation passed");
})().catch((error) => { console.error(error); process.exitCode = 1; });
