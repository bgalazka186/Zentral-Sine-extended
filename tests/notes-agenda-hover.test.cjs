"use strict";
const assert = require("node:assert/strict");
const { createFakeZen } = require("./helpers/fake-zen-browser.cjs");
const C = require("../additional/notes/calendar/ZentralNotesCalendar.js");
const PREF = "zen.workspace.zentral.notes.agenda_folder";
const MARK = "bgalazka-notes-agenda-item";
const card = h => h.document.getElementById("bgalazka-notes-agenda-card");
const tabFor = (h, id) => h.document.querySelectorAll(`tab[${MARK}]`).find(t => t.getAttribute("bgalazka-notes-agenda-record-id") === id);
const item = (id, summary, hour = 12) => C.makeItem({ id, summary, start: { dateTime: new Date(C.addDays(C.dayStart(Date.now()), 1) + hour * 3600000).toISOString() }, x: { src: "manual", kind: "reminder" } });
(async () => {
  const h = createFakeZen({ prefs: { [PREF]: true } }); await h.seam.ensureStore(); h.fireTimer(6500); await Promise.resolve();
  const long = "Complete untruncated reminder title " + "longword".repeat(45);
  h.seam.store.items.upsert(item("long", long)); h.seam.store.items.upsert(item("second", "Second title", 13)); h.seam.agendaController.runNow();
  const a = tabFor(h, "long"), b = tabFor(h, "second"); assert.ok(a && b);
  a.getBoundingClientRect = () => ({ left: 0, right: 200, top: 780, bottom: 800, width: 200, height: 20 });
  b.getBoundingClientRect = () => ({ left: 1000, right: 1200, top: 8, bottom: 28, width: 200, height: 20 });
  a.setAttribute("aria-describedby", "existing-description");
  h.emit("mouseover", a); assert.ok(h.fireTimer(350), "hover delay scheduled");
  assert.ok(card(h) && !card(h).hidden); assert.equal(card(h).textContent, long); assert.equal(card(h).getAttribute("role"), "tooltip");
  assert.equal(card(h).getAttribute("popover"), "manual"); assert.match(a.getAttribute("aria-describedby"), /existing-description.*bgalazka-notes-agenda-card/);
  assert.ok(parseFloat(card(h).style.left) >= 200, "left sidebar card opens to its right");
  assert.ok(parseFloat(card(h).style.top) <= h.window.innerHeight - 4, "bottom-edge tooltip is clamped");
  assert.ok(a.getAttribute("tooltiptext").includes(long), "native fallback includes the full title");
  h.emit("mouseout", a, { relatedTarget: card(h) }); h.emit("mouseover", card(h));
  assert.equal(h.fireTimer(150), false, "hovering the tooltip keeps it open");
  h.emit("mouseout", card(h), { relatedTarget: b }); h.emit("mouseover", b); assert.ok(h.fireTimer(350)); assert.equal(card(h).textContent, "Second title");
  assert.ok(parseFloat(card(h).style.left) < 1000, "right sidebar card opens to its left");
  h.seam.store.items.upsert({ ...h.seam.store.items.get("second"), summary: "Changed while hovered" }); h.seam.agendaController.runNow();
  assert.equal(card(h).textContent, "Changed while hovered", "open card reflects projection changes");
  assert.equal(a.getAttribute("aria-describedby"), "existing-description");
  h.emit("mouseout", b, { relatedTarget: null }); assert.ok(h.fireTimer(150)); assert.equal(card(h).hidden, true);
  h.emit("focusin", a); assert.equal(card(h).hidden, false); assert.equal(card(h).textContent, long);
  const nativeTooltip = h.document.createElement("div"); nativeTooltip.id = "tabbrowser-tab-tooltip"; nativeTooltip.triggerNode = a;
  assert.equal(h.emit("popupshowing", nativeTooltip).defaultPrevented, true, "owned open card replaces native tooltip");
  h.emit("keydown", a, { key: "Escape" }); assert.equal(card(h).hidden, true); assert.equal(a.getAttribute("aria-describedby"), "existing-description");
  const foreign = h.window.gBrowser.addTab("https://example.test/"); foreign.setAttribute("title", "foreign title");
  h.emit("mouseover", foreign); assert.equal(card(h).hidden, true); assert.equal(foreign.getAttribute("title"), "foreign title");
  h.emit("mouseover", a); h.emit("mouseout", a, { relatedTarget: foreign }); assert.equal(h.fireTimer(350), false, "leaving before hover delay cancels the card");
  h.emit("focusin", b); h.window.gBrowser.removeTab(b); assert.equal(card(h).hidden, true, "tab removal closes the card");
  h.seam.agendaController.runNow(); const restoredB = tabFor(h, "second"); h.emit("focusin", restoredB); restoredB.remove(); h.triggerMutations();
  assert.equal(card(h).hidden, true, "out-of-band DOM removal closes the card");
  h.emit("focusin", a); h.setPref(PREF, false); assert.equal(card(h).hidden, true, "disable closes the card");
  await h.destroy(); assert.equal(card(h), null); assert.equal(a.getAttribute("aria-describedby"), "existing-description");
  const fallback = createFakeZen({ prefs: { [PREF]: true } });
  fallback.El.prototype.showPopover = function () { throw new Error("unsupported popover"); };
  await fallback.seam.ensureStore(); fallback.fireTimer(6500); await Promise.resolve();
  fallback.seam.store.items.upsert(item("fallback", "Fallback title")); fallback.seam.agendaController.runNow();
  fallback.emit("focusin", tabFor(fallback, "fallback"));
  assert.equal(card(fallback).hidden, false); assert.equal(card(fallback).hasAttribute("popover"), false, "failed top-layer entry falls back to positioned content");
  await fallback.destroy();
  console.log("Agenda hover card lifecycle and accessibility passed");
})().catch(error => { console.error(error); process.exitCode = 1; });
