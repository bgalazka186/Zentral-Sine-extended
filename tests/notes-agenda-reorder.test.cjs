"use strict";
const assert = require("node:assert/strict");
const { createFakeZen } = require("./helpers/fake-zen-browser.cjs");
const C = require("../additional/notes/calendar/ZentralNotesCalendar.js");
(async () => {
  const h = createFakeZen({ prefs: { "zen.workspace.zentral.notes.agenda_folder": true } });
  await h.seam.ensureStore(); h.fireTimer(6500); await Promise.resolve();
  const start = C.addDays(C.dayStart(Date.now()), 1) + 12 * 3600000;
  for (let i = 0; i < 3; i++) h.seam.store.items.upsert(C.makeItem({ id: "order-" + i, summary: "Order " + i, start: { dateTime: new Date(start + i * 1000).toISOString() }, x: { src: "manual", kind: "reminder" } }));
  h.seam.store.items.upsert(C.makeItem({ id: "next-day", summary: "Next day", start: { dateTime: new Date(start + 86400000).toISOString() }, x: { src: "manual", kind: "reminder" } }));
  h.seam.agendaController.runNow();
  const entries = h.seam.agendaApi.list(), day = entries.find(e => e.kind === "day").key;
  const keys = Array.from(entries.filter(e => e.kind === "item" && e.parent === day), e => e.key);
  assert.equal(keys.length, 3); const wanted = keys.slice().reverse(), native = h.window.gBrowser.moveTabBefore; let moves = 0, schedules = 0;
  h.window.gBrowser.moveTabBefore = (...args) => { moves++; return native(...args); };
  const schedule = h.seam.agendaController.schedule; h.seam.agendaController.schedule = () => { schedules++; };
  assert.equal(h.seam.agendaApi.reorder(day, wanted), true); assert.ok(moves > 0, "reorder uses the native helper");
  assert.equal(schedules, 0, "own TabMove is ignored");
  assert.deepEqual(Array.from(h.seam.agendaApi.list().filter(e => e.kind === "item" && e.parent === day), e => e.key), wanted);
  moves = 0; assert.equal(h.seam.agendaApi.reorder(day, wanted), true); assert.equal(moves, 0, "already ordered is a no-op");
  const days = Array.from(entries.filter(e => e.kind === "day"), e => e.key);
  assert.equal(days.length, 2); moves = 0;
  assert.equal(h.seam.agendaApi.reorder("", days.slice().reverse()), true); assert.ok(moves, "day folders also use the native helper");
  assert.deepEqual(Array.from(h.seam.agendaApi.list().filter(e => e.kind === "day"), e => e.key), days.slice().reverse());
  h.window.gBrowser.moveTabBefore = () => {};
  assert.equal(h.seam.agendaApi.reorder(day, keys), false, "a no-op native helper does not silently bypass bookkeeping");
  h.window.gBrowser.moveTabBefore = () => { throw Error("native move refused"); };
  assert.equal(h.seam.agendaApi.reorder(day, keys), false, "native refusal is reported without unsafe DOM fallback");
  assert.deepEqual(Array.from(h.seam.agendaApi.list().filter(e => e.kind === "item" && e.parent === day), e => e.key), wanted);
  delete h.window.gBrowser.moveTabBefore;
  assert.equal(h.seam.agendaApi.reorder(day, keys), true, "DOM fallback is used when native helper is absent");
  assert.deepEqual(Array.from(h.seam.agendaApi.list().filter(e => e.kind === "item" && e.parent === day), e => e.key), keys);
  const eventTab = h.document.querySelector("tab[bgalazka-notes-agenda-item]");
  h.emit("TabMove", eventTab); assert.equal(schedules, 1, "external moves still schedule reconciliation after a failed reorder");
  h.seam.agendaController.schedule = schedule; await h.destroy(); console.log("Agenda native reorder tests passed");
})().catch(e => { console.error(e); process.exitCode = 1; });
