"use strict";
const assert = require("node:assert/strict"), fs = require("node:fs"), vm = require("node:vm");
const flavors = require("../additional/notes/flavors/ZentralNotesFlavors.js");
const window = { __zentralNotesTestSeam: {}, __zentralNotesParts: { "notes-flavors": flavors }, ZentralRuntime: { register() {} } }; window.window = window;
vm.runInNewContext(fs.readFileSync(require.resolve("../additional/notes/ZentralNotes.uc.js"), "utf8"), { window, globalThis: { Services: {} }, ChromeUtils: {}, URL, Date, JSON, Math, Promise, RegExp, Number, Map, Set, console });
const c = window.__zentralNotesTestSeam.core;
const body = '-# small print\n';
assert.deepEqual(Array.from(c.markdownExportWarnings(body, { flavor: 'mixed' })), ['small print']);
assert.deepEqual(Array.from(c.markdownExportWarnings(body, { flavor: 'github' })), [], 'GitHub mode does not interpret O01');
assert.deepEqual(Array.from(c.markdownExportWarnings(body, { flavor: 'mixed', ignore: 'O01' })), [], 'ignored feature IDs suppress O01');
assert.deepEqual(Array.from(c.markdownExportWarnings(body, { flavor: 'mixed', ignore: '-#' })), [], 'ignored literal syntax suppresses O01');
const opts = { flavor: 'github', ignore: '' };
assert.equal(c.portableMarkdownExportBody({ id: 'n1', body }, [], new Map(), [], opts), body);
assert.equal(c.portableMarkdownExportBody({ id: 'n1', body, flavor: 'mixed' }, [], new Map(), [], opts), 'small print\n', 'note flavor overrides global flavor');
assert.equal(c.portableMarkdownExportBody({ id: 'n1', body, flavor: 'github' }, [], new Map(), [], { flavor: 'mixed' }), body, 'per-note disabled flavor is honored');
assert.equal(c.portableMarkdownExportBody({ id: 'n1', body }, [], new Map(), [], { flavor: 'mixed', ignore: 'O01' }), body);
assert.equal(c.markdownExportBody({ id: 'n1', body, flavor: 'github' }, [], new Map(), [], 'raw', { flavor: 'mixed' }), body);
const nested = '::: note Title\n-# tiny\n:::\n';
assert.match(c.portableMarkdownExportBody({ id: 'n1', body: nested }, [], new Map(), [], { flavor: 'mixed', ignore: 'O01' }), /> -# tiny/, 'ignore settings reach nested containers');
assert.match(c.portableMarkdownExportBody({ id: 'n1', body: nested }, [], new Map(), [], { flavor: 'mixed' }), /> tiny/, 'active small print in a container is converted');
const exported = c.markdownExportFile({ id: 'n1', body, flavor: 'github', created: 1760000000000, updated: 1760000000000 }, [], new Map(), [], 'portable', { flavor: 'mixed' });
assert.match(exported, /\n-# small print\n$/, 'the Markdown file uses the note-specific mode');
const styles = 'H~2~O and X^2^';
const scan = (text, options) => Array.from(c.markdownExportWarnings(text, options));
const convert = (text, options, extra = {}) => c.portableMarkdownExportBody({ id: 'n1', body: text, ...extra }, [], new Map(), [], options);
assert.deepEqual(scan(styles, { flavor: 'mixed' }), ['subscript / superscript']);
assert.equal(convert(styles, { flavor: 'mixed' }), 'H<sub>2</sub>O and X<sup>2</sup>');
assert.deepEqual(scan(styles, { flavor: 'github' }), ['single-tilde strike']);
assert.equal(convert(styles, { flavor: 'github' }), 'H~~2~~O and X^2^');
assert.equal(convert(styles, { flavor: 'mixed', tilde: 'strike' }), 'H~~2~~O and X<sup>2</sup>');
assert.deepEqual(scan(styles, { flavor: 'obsidian' }), []);
assert.equal(convert(styles, { flavor: 'reddit' }), styles);
assert.equal(convert(styles, { flavor: 'mixed', ignore: 'A13 A15' }), styles);
assert.equal(convert(styles, { flavor: 'mixed', ignore: '~ ^' }), styles);
assert.equal(convert(styles, { flavor: 'mixed', ignore: 'H~2~O' }), 'H~2~O and X<sup>2</sup>');
assert.equal(convert(styles, { flavor: 'mixed' }, { flavor: 'github' }), 'H~~2~~O and X^2^');
const escaped = String.raw`H\~2\~O and X\^2\^`;
assert.deepEqual(scan(escaped, { flavor: 'mixed' }), []);
assert.equal(convert(escaped, { flavor: 'mixed' }), escaped);
assert.equal(convert('`H~2~O` [example](https://example.test/X^2^)', { flavor: 'mixed' }), '`H~2~O` [example](https://example.test/X^2^)');
assert.equal(convert(styles, { flavor: 'mixed+github' }), 'H~~2~~O and X<sup>2</sup>');
assert.equal(convert(styles, { flavor: 'mixed+reddit' }), 'H<sub>2</sub>O and X^2^');
assert.equal(convert(styles, { flavor: 'github', ignore: 'A09' }), styles);
assert.equal(convert(styles, { flavor: 'mixed', ignore: '2' }), 'H<sub>2</sub>O and X<sup>2</sup>', 'ignored letters or digits do not escape delimiters');
const partiallyEscaped = String.raw`H\~2~O and X^2\^`;
assert.deepEqual(scan(partiallyEscaped, { flavor: 'mixed' }), []);
assert.equal(convert(partiallyEscaped, { flavor: 'mixed' }), partiallyEscaped);
const pairedBackslashes = String.raw`H\\~2~O`;
assert.deepEqual(scan(pairedBackslashes, { flavor: 'mixed' }), ['subscript / superscript']);
assert.equal(convert(pairedBackslashes, { flavor: 'mixed' }), String.raw`H\\<sub>2</sub>O`);
const otherExtension = '==Active== and H~2~O and X^2^';
assert.equal(convert(otherExtension, { flavor: 'mixed', ignore: 'A13 A15' }), '**Active** and H~2~O and X^2^', 'inactive scripts remain literal even when another rule selects portable mode');
console.log('Markdown export flavor tests passed');
