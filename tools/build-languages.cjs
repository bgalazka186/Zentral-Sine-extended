#!/usr/bin/env node
/* OW-79: one list of the interface languages, generated from the directory.
 *
 * Adding a language is meant to be a data file, `additional/notes/i18n/xx.js`, and nothing else. Before this tool that
 * was not true: `ZentralNotes.uc.js` had one `loadOptional("…/en.js")` line per language, the calendar core carried
 * `NOTES_LANGUAGES = ["en", "pl"]`, and the settings menu had its own hardcoded `[["en", "English"], ["pl", "Polski"]]`.
 * A new file therefore needed three JS edits in two files, and the one nobody remembered was the menu.
 *
 * This tool reads the directory and writes `additional/notes/i18n/registry.js`, a tiny module that names every file it
 * found. The runtime loads the registry and then loads each language it lists; the settings menu is built from what
 * registered. So a new file appears everywhere by existing — the only step left is running this tool (and the build
 * already does), which is the same rule the standalone bundles and the z-map follow.
 *
 * Usage:
 *   node tools/build-languages.cjs            write the registry
 *   node tools/build-languages.cjs --check    change nothing; exit 1 if the registry is stale
 */
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const DIR = path.join(ROOT, "additional/notes/i18n");
const OUT = path.join(DIR, "registry.js");
const CODE_RE = /^[a-z]{2,3}(?:-[A-Za-z]{2,4})?$/;

// One entry per `xx.js` beside the tool. `en` must be there: it is the fallback every other table is measured against.
function discover() {
  const files = fs.readdirSync(DIR).filter((name) => name.endsWith(".js") && name !== "registry.js");
  const codes = files
    .map((name) => name.slice(0, -3))
    .filter((code) => CODE_RE.test(code))
    .sort();
  if (!codes.includes("en")) throw new Error("i18n/en.js is the fallback language and must exist");
  return codes;
}

function render(codes) {
  return `// GENERATED by tools/build-languages.cjs — do not edit. Add a language by adding i18n/<code>.js and running the tool.
// OW-79: the one list of interface languages. The sheet loads every code named here and nothing else, so a language
// appears in the settings menu by existing as a file.
(function () {
  "use strict";
  const table = Object.freeze({ languages: Object.freeze(${JSON.stringify(codes)}), fallback: "en" });
  if (typeof window !== "undefined" && window) {
    window.__zentralNotesLangRegistry = table;
    if (window.ZentralModuleLoader && typeof window.ZentralModuleLoader.define === "function") {
      window.ZentralModuleLoader.define("notes-lang-registry", table);
    }
  }
  if (typeof module !== "undefined" && module.exports) module.exports = table;
})();
`;
}

function main() {
  const check = process.argv.includes("--check");
  const codes = discover();
  const text = render(codes);
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (check) {
    if (current !== text) {
      console.error("i18n/registry.js is stale: run node tools/build-languages.cjs");
      process.exit(1);
    }
    console.log(`language registry is current: ${codes.join(", ")}`);
    return;
  }
  if (current !== text) {
    fs.writeFileSync(OUT, text);
    console.log(`language registry written: ${codes.join(", ")}`);
  } else {
    console.log(`language registry unchanged: ${codes.join(", ")}`);
  }
}

if (require.main === module) main();
module.exports = { discover, render, OUT };
