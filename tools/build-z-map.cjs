#!/usr/bin/env node
"use strict";
/* Generates z-heights_map.md from the source: every z-index in CSS and JS, grouped by layer,
 * plus every popover / top-layer user. Run `node tools/build-z-map.cjs` after changing any
 * z-index; `--check` (used by tests/z-heights.test.cjs) fails when the file is stale.
 * Only the TIERS and TOP_LAYER_NOTES tables below are hand-written. */
const fs = require("node:fs"),
  path = require("node:path");
const root = path.resolve(__dirname, "..");
const SKIP = new Set([".git", "node_modules", "upstream", "patches", "docs", "tests", "tools"]);
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP.has(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(css|js)$/.test(e.name) && !/\.standalone\.uc\.js$/.test(e.name)) files.push(p);
  }
})(root);

// Names for the shared global layers (value -> what lives there). Everything else is local.
const TIERS = {
  2147483647: "Highest normal layer: Zentral settings window, corner-tile badges, developer and loader error overlays",
  2147483646: "RSS reader card (fallback only; see Top layer)",
  2147483645: "Notes floating card (standalone / shortcut)",
  2147483643: "Big Preview (fallback only; see Top layer)",
  2147483642: "Dock ghost while a floating panel is dragged",
  2147483640: "Reveal edge and invisible drag shields",
  2147483638: "Dock ghost (floating panel preview)",
  2147483603: "Triple View drag handle",
  2147483601: "Super Pin panel",
  2147483600: "Zentral panel root",
  2147483550: "Vertical-bar apps toolbar",
  2147483500: "Autohidden vertical bar",
  999999: "Opposite-docking panel overlays",
};
const TOP_LAYER_NOTES = {
  "additional/video/controllers/ZentralVideoEnlarge.js": "Big Preview: popover=\"manual\", shown with showPopover() while enlarged",
  "additional/notes/ZentralNotes.uc.js": "Notes standalone card: popover=\"manual\" only WHILE Notes has the focus (raise on focus / press inside, drop and remove the attribute on any outside press), so it is above Big Preview unless Big Preview was pressed",
  "additional/rss/ZentralRssDisplay.uc.js": "RSS reader card: popover=\"manual\", re-shown on every showCard so it sits above Big Preview",
};

const rel = (f) => path.relative(root, f).split(path.sep).join("/");
const rows = [];
for (const file of files) {
  const text = fs.readFileSync(file, "utf8");
  if (file.endsWith(".css")) {
    // Blank out comments but keep newlines so line numbers stay right.
    const clean = text.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "));
    const stack = [];
    let buf = "", line = 1, decl = "";
    for (const ch of clean) {
      if (ch === "{") { stack.push(buf.replace(/\s+/g, " ").trim()); buf = ""; decl = ""; }
      else if (ch === "}") { stack.pop(); buf = ""; decl = ""; }
      else if (ch === ";") {
        const m = /(?:^|\s)z-index\s*:\s*(-?\d+)\s*(!important)?\s*$/.exec(decl);
        if (m) rows.push({ value: Number(m[1]), file: rel(file), line, where: stack[stack.length - 1] || "(root)", important: !!m[2] });
        buf = ""; decl = "";
      } else { buf += ch; decl += ch; }
      if (ch === "\n") line++;
    }
  } else {
    text.split("\n").forEach((src, i) => {
      for (const m of src.matchAll(/z-?[iI]ndex["']?\s*[:=]\s*["']?(-?\d{1,10})/g)) {
        if (/cs\.zIndex|\$\{/.test(src.slice(Math.max(0, m.index - 12), m.index + 20))) continue;
        rows.push({ value: Number(m[1]), file: rel(file), line: i + 1, where: src.trim().slice(0, 70).replace(/\|/g, "\\|"), important: false, js: true });
      }
    });
  }
}
const popovers = [];
for (const file of files) {
  const text = fs.readFileSync(file, "utf8");
  if (/showPopover\s*\(/.test(text)) popovers.push(rel(file));
}

const esc = (s) => s.replace(/\|/g, "\\|");
const global = rows.filter((r) => r.value >= 1000).sort((a, b) => b.value - a.value || a.file.localeCompare(b.file) || a.line - b.line);
const local = rows.filter((r) => r.value < 1000);
let md = `# Z-heights map

Generated by \`node tools/build-z-map.cjs\` from the source. **Do not edit by hand**; change a
z-index in the code, then regenerate. \`tests/z-heights.test.cjs\` fails when this file is stale or
when the ordering rules below are broken.

## How stacking works here

1. **Top layer beats every z-index.** An element shown with \`showPopover()\` (or \`showModal()\`) is
   painted above everything that is not also in the top layer, whatever its z-index. Among top-layer
   elements the one added **later** is on top. Top-layer users in this mod:

${popovers.map((f) => `   - \`${f}\`: ${TOP_LAYER_NOTES[f] || "uses showPopover()"}`).join("\n")}

   To put something above Big Preview, make it a popover and show it after Big Preview (the RSS card
   does this on every show). Raising a z-index does nothing against the top layer.
2. **Normal layers** are ordered by z-index inside the same stacking context. Values below are the
   shared "global" layers near the 32-bit limit (\`2147483647\`); lower numbers are local to a component.
3. A z-index only competes with elements in the **same stacking context**. A transformed, filtered or
   \`contain: paint\` ancestor starts a new one, which is why the notes sheet (z-index 40) is placed inside
   the panel slider instead of at the document root.

## Ordering rules (tested)

- Settings window and corner tiles (2147483647) are above the RSS card (2147483646) and the Notes floating card (2147483645).
- The Notes floating card is above Big Preview's fallback value (2147483643) and the panel root (2147483600).
- The RSS card fallback is above every panel layer (panel root 2147483600, reveal edge and pills 2147483640-2147483642).
- RSS card is a top-layer popover shown after Big Preview, so it is above Big Preview whenever both are visible.
- The Notes standalone card is a top-layer popover only while it is focused: it is above Big Preview until Big Preview (or anything outside Notes) is pressed, then it drops to its normal layer (2147483645) below Big Preview. Notes inside a panel is never a popover.

## Global layers (z-index 1000 and above)

| z-index | Role | Where | File:line |
| ---: | --- | --- | --- |
`;
for (const r of global) {
  md += `| ${r.value} | ${TIERS[r.value] || ""} | ${r.js ? "inline style: " : ""}\`${esc(r.where)}\` | ${r.file}:${r.line} |\n`;
}
md += `\n## Local layers (below 1000)\n\nOrdering inside one component. Listed by file; values only matter relative to siblings.\n\n<details>\n<summary>${local.length} local z-index declarations</summary>\n\n| File | Line | z-index | Selector / code |\n| --- | ---: | ---: | --- |\n`;
for (const r of local.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line)) {
  md += `| ${r.file} | ${r.line} | ${r.value} | \`${esc(r.where)}\` |\n`;
}
md += `\n</details>\n`;

const out = path.join(root, "z-heights_map.md");
if (require.main === module) {
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
    if (current !== md) {
      console.error("z-heights_map.md is stale: run node tools/build-z-map.cjs");
      process.exit(1);
    }
    console.log("z-heights_map.md is up to date");
  } else {
    fs.writeFileSync(out, md);
    console.log(`z-heights_map.md written: ${global.length} global layers, ${local.length} local, ${popovers.length} top-layer users`);
  }
}
module.exports = { rows, md };
